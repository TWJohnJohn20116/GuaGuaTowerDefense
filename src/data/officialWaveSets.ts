export const OFFICIAL_WAVE_MOD_ID = 'official-waves';

function wave(groups: { type: EnemyType; count: number }[], reward: number): WaveConfig {
  return {
    enemies: groups.map((group, index) => ({
      type: group.type,
      count: group.count,
      delay: index === 0 ? 0 : 700,
    })),
    reward,
  };
}

