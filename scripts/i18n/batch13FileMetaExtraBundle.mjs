export function formatFileMetaExtraBlock(loc) {
  const data = getFileMetaExtra(loc);
  const lines = Object.keys(FILE_META_EXTRA_KEYS).map(
    (k) => `      ${k}: ${JSON.stringify(data[k])},`,
  );
  return `    fileMetaExtra: {\n${lines.join('\n')}\n    },`;
}
