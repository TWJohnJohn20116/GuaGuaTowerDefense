export function getDevUi(loc) {
  if (loc === 'zh-TW') return ZH;
  if (loc === 'zh-CN') return ZH_CN;
  if (loc === 'ja') return JA;
  if (loc === 'ko') return KO;
  if (loc === 'de') return DE;
  return EN;
}

export function formatDevUiBlock(obj, indent = 4) {
  const sp = ' '.repeat(indent);
  return Object.entries(obj)
    .map(([k, v]) => `${sp}${k}: ${JSON.stringify(v)},`)
    .join('\n');
}
