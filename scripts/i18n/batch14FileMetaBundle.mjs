const MAP = {
  'zh-TW': ZH, 'zh-CN': ZH, en: EN, ja: JA, ko: KO, de: DE, fr: FR, es: ES, ru: RU, pt: PT,
};

export function getFileMeta(loc) {
  return MAP[loc] ?? EN;
}

export function formatFileMetaBlock(loc) {
  const data = getFileMeta(loc);
  const lines = FILE_META_KEYS.map((k) => `      ${k}: ${JSON.stringify(data[k])},`);
  return `    fileMeta: {\n${lines.join('\n')}\n    },`;
}

