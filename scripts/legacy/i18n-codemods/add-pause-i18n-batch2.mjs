const LOCALE_MAP = {
  'zh-TW': ZH,
  'zh-CN': ZH,
  en: EN,
  ja: JA,
  ko: KO,
  fr: EN,
  de: EN,
  es: EN,
  ru: EN,
  pt: EN,
};

const locales = ['zh-TW', 'zh-CN', 'en', 'ja', 'ko', 'fr', 'de', 'es', 'ru', 'pt'];

for (const loc of locales) {
  const file = path.join('src/i18n/locales', `${loc}.ts`);
  let s = fs.readFileSync(file, 'utf8');
  if (s.includes('pauseGoalEndlessSurvival:')) {
    console.log('skip', loc);
    continue;
  }
  const vals = LOCALE_MAP[loc] ?? EN;
  const block = Object.entries(vals)
    .map(([k, v]) => `    ${k}: '${String(v).replace(/'/g, "\\'")}',`)
    .join('\n');

  s = s.replace(/(\s+pauseDiffCustom: '[^']*',)/, `$1\n${block}`);
  fs.writeFileSync(file, s, 'utf8');
  console.log('patched', loc);
}

