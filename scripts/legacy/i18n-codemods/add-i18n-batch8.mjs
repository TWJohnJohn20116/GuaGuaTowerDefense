const locales = ['zh-TW', 'zh-CN', 'en', 'ja', 'ko', 'fr', 'de', 'es', 'ru', 'pt'];

for (const loc of locales) {
  const file = path.join(ROOT, `${loc}.ts`);
  let s = fs.readFileSync(file, 'utf8');

  // encyclopedia batch7+8
  if (!s.includes('fileDetailSelectHintLine1:')) {
    const enc = ENC_MAP[loc] ?? ENC_EN;
    const block = Object.entries(enc).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join('\n');
    s = s.replace(/(\s+iconLibClearFilter: [^,]+,)/, `$1\n${block}`);
    console.log('enc', loc);
  } else if (!s.includes('sourceLinksTitle:')) {
    const extra = ['sourceLinksTitle', 'sourceLinksHint', 'fileTreeTitle', 'fileCategoryRoot',
      'iconCatCurrency', 'iconCatNavigation', 'iconCatGameState', 'iconCatCombat', 'iconCatTools',
      'iconCatOverlay', 'iconCatSettings', 'iconCatEnemy', 'iconCatEffects', 'iconCatTheme',
      'iconCatAchievement', 'iconCatShapes', 'iconCatOther'];
    const enc = ENC_MAP[loc] ?? ENC_EN;
    const block = extra.map((k) => `    ${k}: ${JSON.stringify(enc[k])},`).join('\n');
    s = s.replace(/(\s+fileListSortBy: [^,]+,)/, `$1\n${block}`);
    console.log('enc-extra', loc);
  }

  // game HUD keys
  if (!s.includes('wavePreviewTotalHP:')) {
    const game = GAME_MAP[loc] ?? GAME_EN;
    const block = Object.entries(game).map(([k, v]) => `    ${k}: ${JSON.stringify(v)},`).join('\n');
    s = s.replace(/(\s+moreEnemies: [^,]+,)/, `$1\n${block}`);
    console.log('game-hud', loc);
  }

  // settings hud + navDesc + menuMusic
  if (!s.includes('hud: {')) {
    const insert = [hudBlock(loc), navDescBlock(loc), menuMusicBlock(loc)].join('\n');
    s = s.replace(/(\s+actions: \{[\s\S]*?\n\s+\},)\n(\s+\},)/, `$1\n${insert}\n$2`);
    console.log('settings-hud', loc);
  }

  // sabotage ability
  if (s.includes("explode: '") && !s.includes('sabotage:')) {
    const sabotage = loc === 'zh-TW' || loc === 'zh-CN' ? '破壞防禦塔' : 'Sabotage towers';
    s = s.replace(/(\s+explode: [^,]+,)/, `$1\n      sabotage: ${JSON.stringify(sabotage)},`);
    console.log('sabotage', loc);
  }

  fs.writeFileSync(file, s, 'utf8');
}

